"""Build a bounded offline dictionary from ECDICT (MIT); no runtime translation API."""
import csv, hashlib, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
MINI = ROOT / 'miniprogram'
SOURCE = ROOT / 'references/dictionary/ecdict.csv'
token = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*")
valid = re.compile(r"^[a-z]+(?:'[a-z]+)*$")
words = set()
for folder in ['papers', 'data/words', 'pages', 'utils']:
    for file in (MINI / folder).rglob('*'):
        if file.suffix in ['.js', '.wxml']:
            words.update(w.lower().replace('’', "'") for w in token.findall(file.read_text('utf-8')))
records = {}
with SOURCE.open(encoding='utf-8-sig', newline='') as f:
    for row in csv.DictReader(f):
        word = row['word'].lower().replace('’', "'")
        if valid.fullmatch(word) and len(word) <= 60:
            # Prefer an actual lowercase entry over a same-spelling proper noun.
            if word not in records or row['word'] == word:
                records[word] = row
selected = set(words & records.keys())
selected.update(w for w, r in records.items() if r['bnc'].isdigit() and 0 < int(r['bnc']) <= 8000)
# Add explicitly recorded lemmas, not guessed suffix stripping.
for word in list(selected):
    for form in records[word]['exchange'].split('/'):
        if form.startswith('0:'):
            selected.update(w for w in form[2:].split(',') if w in records)
packs = [{} for _ in range(4)]
def bucket(word):
    n = 0
    for char in word:
        n = (n * 31 + ord(char)) & 0xffffffff
    return n % 4
for word in sorted(selected):
    row = records[word]
    meaning = row['translation'].replace('\\n', '\n').strip()
    if not meaning:
        continue
    lemma = next((f[2:].split(',')[0] for f in row['exchange'].split('/') if f.startswith('0:')), '')
    packs[bucket(word)][word] = [row['phonetic'][:100], meaning[:1200], lemma if lemma in selected else '']
for n, data in enumerate(packs):
    folder = MINI / ('dictionary/pack' + str(n))
    folder.mkdir(parents=True, exist_ok=True)
    (folder / 'entries.js').write_text('/* ECDICT, MIT. See /dictionary-LICENSE.txt. Generated by tools/build-dictionary.py. */\nmodule.exports=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    (folder / 'ready.js').write_text('Page({})\n', encoding='utf-8')
    (folder / 'ready.json').write_text('{}\n', encoding='utf-8')
    (folder / 'ready.wxml').write_text('<view>词典资料</view>\n', encoding='utf-8')
    (folder / 'ready.wxss').write_text('/* Resource package */\n', encoding='utf-8')
app_path = MINI / 'app.json'
app = json.loads(app_path.read_text('utf-8'))
app['subPackages'] = [p for p in app['subPackages'] if not p['root'].startswith('dictionary/')]
app['subPackages'] += [dict(root='dictionary/pack'+str(n), name='dictionary'+str(n), pages=['ready']) for n in range(4)]
app_path.write_text(json.dumps(app, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
config_path = ROOT / 'project.config.json'
config = json.loads(config_path.read_text('utf-8'))
includes = config.setdefault('packOptions', {}).setdefault('include', [])
if not any(p.get('value') == 'dictionary' for p in includes):
    includes.append(dict(type='folder', value='dictionary'))
config_path.write_text(json.dumps(config, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
(MINI / 'dictionary-LICENSE.txt').write_bytes((ROOT / 'references/dictionary/LICENSE').read_bytes())
report = dict(source='https://github.com/skywind3000/ECDICT', sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
              entries=sum(map(len, packs)), corpusTokens=len(words), corpusMatched=len(words & set().union(*packs)),
              packageBytes=[(MINI / f'dictionary/pack{n}/entries.js').stat().st_size for n in range(4)])
(ROOT / 'references/dictionary/build-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print(json.dumps(report, ensure_ascii=False))
